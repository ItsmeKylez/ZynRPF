// Component smoke test: renders the real PendingGrid in headless Chromium with a STUBBED fetch (the server is not involved).
// It checks the UI only: rows, New badge, load more, error text. Run: node scripts/test-pending-grid.mjs
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const require = createRequire(import.meta.url);
const TOOLS = process.env.TOOLS || "/opt/npm-tools/node_modules";
const esbuild = require(TOOLS + "/esbuild"), { chromium } = require(TOOLS + "/playwright");
const dir = mkdtempSync(join(tmpdir(), "pg-"));
const entry = join(dir, "entry.tsx");
writeFileSync(entry, `import { createRoot } from "react-dom/client";
import { PendingGrid } from ${JSON.stringify(process.cwd() + "/web/src/PendingGrid")};
(window as any).show = (path: string) => createRoot(document.getElementById("r")!).render(<PendingGrid workspaceId="w" versionId="v" path={path} stamp="1" />);`);
const out = await esbuild.build({ entryPoints: [entry], bundle: true, write: false, jsx: "automatic", define: { "process.env.NODE_ENV": '"production"' }, nodePaths: [TOOLS] });
const b = await chromium.launch(); const page = await b.newPage();
await page.route("http://t.test/**", (route) => {
  if (!route.request().url().includes("/api/v1/")) return route.fulfill({ status: 200, contentType: "text/html", body: '<div id="r"></div>' });
  const u = new URL(route.request().url()), p = u.searchParams.get("path"), cur = Number(u.searchParams.get("cursor"));
  if (p === "/gone") return route.fulfill({ status: 404, contentType: "application/json", body: JSON.stringify({ error: { code: "not_found", message: "No such folder.", next_step: "Go up.", request_id: "x" } }) });
  const all = [{ name: "dir1", kind: "directory", size: 0, new: false }, { name: "renamed.txt", kind: "file", size: 2048, new: false }, { name: "added.bin", kind: "file", size: 5, new: true }];
  const big = p === "/big" ? Array.from({ length: 250 }, (_, i) => ({ name: "f" + String(i).padStart(3, "0"), kind: "file", size: 1, new: false })) : all;
  const items = big.slice(cur, cur + Number(u.searchParams.get("limit")));
  route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ path: p, total: big.length, entries: items }) });
});
await page.goto("http://t.test/"); await page.addScriptTag({ content: out.outputFiles[0].text });
await page.evaluate(() => window.show("/"));
await page.waitForSelector("table");
assert.equal(await page.locator("tbody tr").count(), 3);
assert.match(await page.locator("tbody tr").nth(2).innerText(), /added\.bin[\s\S]*new/i);
console.log("size cell:", JSON.stringify(await page.locator("tbody tr").nth(1).innerText())); assert.match(await page.locator("tbody tr").nth(1).innerText(), /renamed\.txt[\s\S]*2/);
await page.reload(); await page.addScriptTag({ content: out.outputFiles[0].text });
await page.evaluate(() => window.show("/big")); await page.waitForFunction(() => document.querySelectorAll("tbody tr").length === 200);
await page.getByRole("button", { name: /load more|more/i }).click();
await page.waitForFunction(() => document.querySelectorAll("tbody tr").length === 250);
await page.reload(); await page.addScriptTag({ content: out.outputFiles[0].text });
await page.evaluate(() => window.show("/gone"));
await page.waitForSelector("text=does not exist after your pending changes");
await b.close();
console.log("pending grid component test passed (stubbed server)");
